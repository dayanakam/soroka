def queries_for(style_ids: list[str], categories: list[str]) -> list[tuple[str, str, str]]:
    """(стиль, категория, поисковая фраза) — по всем выбранным стилям и категориям."""
    out: list[tuple[str, str, str]] = []
    for sid in style_ids:
        s = STYLES.get(sid)
        if not s:
            continue
        for cat, phrases in s["q"].items():
            if cat not in categories:
                continue
            for phrase in phrases:
                out.append((sid, cat, phrase))
    return out
